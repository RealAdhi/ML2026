"""Build candidate/feature tables for the training and student-test partitions.

Output (git-ignored, regenerated by this script): data/processed/{train,student_test}.pkl
Each pickle holds {"df": candidate rows, "info": {trip: {ref_arc, ref_pos, n}}}.
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "src"))

import joblib
import pandas as pd
from joblib import Parallel, delayed

from pathsnap.candidates import generate
from pathsnap.data import list_trips, load_trip


def one(root, tid):
    tr = load_trip(root, tid)
    df, info = generate(tr)
    return tid, df, info


if __name__ == "__main__":
    out = os.path.join(ROOT, "data", "processed")
    os.makedirs(out, exist_ok=True)
    for part in ("train", "student_test"):
        root = os.path.join(ROOT, part)
        res = Parallel(n_jobs=8)(delayed(one)(root, t) for t in list_trips(root))
        df = pd.concat([r[1] for r in res], ignore_index=True)
        info = {r[0]: r[2] for r in res}
        joblib.dump({"df": df, "info": info}, os.path.join(out, f"{part}.pkl"))
        pos = df.groupby(["trip", "obs"]).label.max()
        print(part, "trips", len(info), "obs", len(pos), "rows", len(df),
              "candidate miss rate", round(1 - pos.mean(), 4),
              "nearest-arc top1", round(df[df.d_rank == 0].label.mean(), 4))
